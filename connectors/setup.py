def device(w, v, kind, name, facts):
    """One device, its own record: a new version only when what it is changes (an OS update), not when it connects."""
    text = "\n".join(f"{k}: {val}" for k, val in facts.items() if val not in (None, ""))
    v.add(w, f"device:{kind}:{name}", "device", f"{kind}: {name}", f"{name}\n{text}".strip(), None,
          {"group": "devices", "tool": kind, "device": name})


def devices(w, v):
    out = run(["xcrun", "devicectl", "list", "devices", "--quiet", "--json-output", "/dev/stdout"], timeout=60)
    try:
        listed = json.loads(out[out.index("{"):]) if out and "{" in out else {}
    except ValueError:
        listed = {}
    for d in (listed.get("result") or {}).get("devices") or []:
        dp, hp, cp = d.get("deviceProperties") or {}, d.get("hardwareProperties") or {}, d.get("connectionProperties") or {}
        if dp.get("name"):
            device(w, v, "phone" if hp.get("deviceType") in ("iPhone", None) else (hp.get("deviceType") or "device").lower(), dp["name"],
                   {"model": hp.get("marketingName"), "type": hp.get("deviceType"), "os": " ".join(x for x in (hp.get("platform"), dp.get("osVersionNumber")) if x),
                    "paired": cp.get("pairingState"), "developer mode": "on" if dp.get("developerModeStatus") == "enabled" else None})
    for line in (run(["adb", "devices", "-l"]) or "").splitlines()[1:]:
        parts = line.split()
        if len(parts) >= 2 and parts[1] == "device":
            info = dict(p.split(":", 1) for p in parts[2:] if ":" in p)
            device(w, v, "phone", info.get("model", "Android device").replace("_", " "), {"type": "Android", "product": info.get("product")})
    sp = run(["system_profiler", "-json", "SPBluetoothDataType", "SPDisplaysDataType", "SPUSBHostDataType"], timeout=90)
    try:
        sp = json.loads(sp) if sp else {}
    except ValueError:
        sp = {}
    for ctl in sp.get("SPBluetoothDataType") or []:
        for group in ("device_connected", "device_not_connected", "device_paired"):
            for entry in ctl.get(group) or []:
                for name, d in entry.items():  # no addresses or serial numbers
                    device(w, v, "bluetooth", name, {"type": d.get("device_minorType"), "vendor": "Apple" if d.get("device_vendorID") == "0x004C" else None})
    for gpu in sp.get("SPDisplaysDataType") or []:
        for d in gpu.get("spdisplays_ndrvs") or []:
            device(w, v, "display", d.get("_name") or "display",
                   {"resolution": d.get("_spdisplays_resolution"), "pixels": d.get("_spdisplays_pixels"),
                    "connection": (d.get("spdisplays_connection_type") or "").replace("spdisplays_", ""),
                    "main": "yes" if d.get("spdisplays_main") == "spdisplays_yes" else None,
                    "mirrored": "yes" if d.get("spdisplays_mirror") == "spdisplays_on" else None})

    def usb(items):
        for d in items or []:
            if d.get("USBKeyHardwareType") == "Removable" or d.get("USBDeviceKeyVendorName"):
                device(w, v, "usb", d.get("_name") or "USB device", {"vendor": d.get("USBDeviceKeyVendorName")})
            usb(d.get("_items"))
    usb(sp.get("SPUSBHostDataType"))


