def scheduled(w, v):
    """crontab, and on Linux the user services systemd runs: the jobs a person set up."""
    cron = run(["crontab", "-l"])
    if cron and cron.strip():
        v.add(w, "installed:crontab", "inventory", "Your crontab", cron, None, {"group": "installed", "tool": "cron"})
    units = run(["systemctl", "--user", "list-unit-files", "--type=service", "--state=enabled", "--no-legend", "--plain"])
    if units and units.strip():
        names = sorted(l.split()[0] for l in units.splitlines() if l.strip())
        v.add(w, "installed:systemd", "inventory", f"{len(names)} services of your own (systemd)", "\n".join(names), None,
              {"group": "installed", "tool": "systemd"})


def system(w, v):
    """What this machine is: its OS and version, for a machine read from another (machines.py)."""
    text = "\n".join(x.strip() for x in (run(["uname", "-srm"]), run(["sw_vers"]), (open("/etc/os-release").read() if os.path.exists("/etc/os-release") else None)) if x)
    if text:
        v.add(w, "machines:system", "inventory", "This machine", text, None, {"group": "machines", "tool": "system"})


def main(parts=None):
    """Every part, or some (`setup.py --layouts`: the layouts and the agent sessions in them, every few minutes).
    One at a time per corpus: a frequent read, a full one and the app's never write this file at once."""
    import fcntl
    NORM.mkdir(parents=True, exist_ok=True)
    with open(NORM.parent / ".setup.lock", "w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        _main(parts)


def _main(parts):
    some = parts is not None
    # a generated file not read again is gone, unless this read didn't look (only the layouts)
    with Writer("setup", AVENUE, forget=lambda old: not some and bool((old.get("meta") or {}).get("generated"))) as w:
        v = Versions()
        for part in parts or PARTS:
            try:
                part(w, v)
            except Exception as e:  # one tool's odd file stops nothing else
                w.notes.setdefault("not_read", {})[part.__name__] = f"{type(e).__name__}: {e}"[:200]
        v.finish(w)


PARTS = (configs, domains, warp, ghostty, tmux, herdr, taiku, agents_open, aerospace, windows, apps, brew, launch_agents, scripts, tailscale, ssh_hosts,
         vms, devices, simulators, scheduled, system)
LAYOUTS = (warp, ghostty, tmux, herdr, taiku, agents_open, aerospace, windows)

if __name__ == "__main__":
    main(LAYOUTS if "--layouts" in sys.argv else None)
