def configs(w, v):
    for group, tool, pats in FILES:
        for pat in pats:
            for p in sorted(glob.glob(str(HOME / pat))):
                if not os.path.isfile(p) or os.path.getsize(p) > 5_000_000:
                    continue
                try:
                    text = open(p, encoding="utf-8", errors="replace").read()
                except OSError:
                    continue
                name = tilde(p)
                v.add(w, f"file:{name}", "config", f"{tool}: {name}", text, from_unix(os.path.getmtime(p)),
                      {"group": group, "tool": tool, "path": name, "lines": text.count("\n") + 1}, prose=p.endswith(".md"))
    for tool, rel in EXTENSIONS:
        p = HOME / rel
        try:
            exts = json.loads(p.read_text())
        except (OSError, ValueError):
            continue
        ids = sorted({str(i.get("id", "") if isinstance(i, dict) else i or "") for e in exts if isinstance(e, dict)
                      for i in [e.get("identifier")]} - {""}) if isinstance(exts, list) else []
        if ids:
            v.add(w, f"extensions:{tool}", "config", f"{tool}: {len(ids)} extensions", "\n".join(ids), from_unix(os.path.getmtime(p)),
                  {"group": "editor", "tool": tool, "path": tilde(p), "lines": len(ids)})


