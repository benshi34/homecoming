def ssh_lines(cfg, depth=0):
    """~/.ssh/config's lines, with its Include files' in their place."""
    try:
        text = cfg.read_text(errors="replace")
    except OSError:
        return []
    out = []
    for line in text.splitlines():
        m = re.match(r"(?i)\s*include\s*[ =]\s*(.+)", line)
        if m and depth < 3:
            for pat in m.group(1).split():
                pat = os.path.expanduser(pat)
                for inc in sorted(glob.glob(pat if os.path.isabs(pat) else str(HOME / ".ssh" / pat))):
                    out += ssh_lines(Path(inc), depth + 1)
        else:
            out.append(line)
    return out


def ssh_hosts(w, v):
    cfg = HOME / ".ssh/config"
    if cfg.exists():
        hosts, cur = [], None
        for line in ssh_lines(cfg):
            m = re.match(r"(?i)\s*(host|match|hostname|user|proxyjump|proxycommand)\s*[ =]\s*(.+)", line)
            if not m:
                continue
            k, val = m.group(1).lower(), m.group(2).strip()
            if k == "host":
                cur = {"host": ", ".join(val.split())}
                hosts.append(cur)
            elif k == "match":  # a Match block's settings are no Host's
                cur = None
            elif cur is not None and k in ("hostname", "user", "proxyjump"):
                cur[k] = val
            elif cur is not None:
                cur["via"] = "a command"
        lines = [h["host"] + "".join(f" {k}={h[k]}" for k in ("hostname", "user", "proxyjump", "via") if h.get(k)) for h in hosts if h["host"] != "*"]
        if lines:
            v.add(w, "machines:ssh", "inventory", f"ssh: {len(lines)} hosts you set up", "\n".join(lines), from_unix(cfg.stat().st_mtime),
                  {"group": "machines", "tool": "ssh", "hosts": len(lines)})


