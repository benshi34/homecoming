FLAG = re.compile(r"""(?<![\w-])(?P<keep>--?(?P<name>[A-Za-z][\w-]{1,40})(?:=|\s+|["']\s*,\s*))(?P<val>"[^"\n]*"|'[^'\n]*'|[^\s"',\]]+)""")
