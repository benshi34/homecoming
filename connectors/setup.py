REDACTED = re.compile(r"\[redacted[^\]]*\]")
SHAPES = [(k, p) for k, p in redact_module.PATTERNS if k not in ("password", "secret")]


def secret_name(name):
    n = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name.strip("\\\"'")).lower().replace("-", "_").replace(".", "_")
    return bool(SECRET_WORDS.search(n)) and not NOT_SECRET_NAME.search(n)


def secret_value(v, prose=False):
    v = v.strip()
    if v.startswith('\\"') and v.endswith('\\"'):
        v = v[2:-2]
    v = v.strip("\"'")
    if re.fullmatch(r"(?i)basic|bearer|token|digest", v):  # the scheme of an Authorization header: HEADER takes its credential
        return False
    if re.fullmatch(r"(?i)(?:(?:cmd|ctrl|alt|shift|meta|option|opt|super|win|hyper)[+-])+\S+(?:\s+\S+)?", v):  # a key chord
        return False
    if len(v) < 6 or REDACTED.search(v) or re.fullmatch(r"[\d.,_:]+|true|false|yes|no|null|none|on|off|nil", v, re.I):
        return False
    if v.startswith(("$", "<", "/", "~", "./", "../", "op://", "keychain", "env:", "%", "{{", "@")) or re.fullmatch(r"[A-Z][A-Z0-9_]{2,}", v):
        return False
    if prose:  # in prose a "name: value" only counts when the value looks like a key
        return not re.search(r"\s", v) and (looks_random(v) or len(v) >= 12 and bool(re.search(r"\d", v)))
    return not re.search(r"\s", v) or bool(re.match(r"(?i)(basic|bearer|token)\s+\S{6,}$", v))


def looks_random(t):
    if len(t) < 24 or sum(c.isdigit() for c in t) < 2 or not re.search(r"[A-Z]", t) or not re.search(r"[a-z]", t):
        return False
    counts = {c: t.count(c) for c in set(t)}
    return -sum(n / len(t) * math.log2(n / len(t)) for n in counts.values()) >= 4.3


def redact(text, prose=False):
    """A config's text with its secrets replaced by [redacted]. prose: a .md file (CLAUDE.md, a skill), where a value
    in prose isn't a setting's ("token: see below"), so only a value that looks random or has a key's shape goes."""
    kept = []

    def hold(s):  # what's already redacted, and $PWD (redact.py reads "PWD =~" as a password)
        kept.append(s)
        return f"\x00{len(kept) - 1}\x00"

    text = REDACTED.sub(lambda m: hold(m.group(0)), text)
    text = text.replace("$PWD", hold("$PWD"))

    def pair(m):
        if not secret_name(m.group("name")) or not secret_value(m.group("val"), prose):
            return m.group(0)
        val = m.group("val")
        q = '\\"' if val.startswith('\\"') else val[0] if val[0] in "\"'" else ""
        return m.group(0)[:m.start("val") - m.start(0)] + q + hold("[redacted]") + q

    def keep_named(m):
        if not secret_name(m.group("name")) or not secret_value(m.group("val"), prose):
            return m.group(0)
        val = m.group("val")
        q = val[0] if val[0] in "\"'" else ""
        return m.group("keep") + q + hold("[redacted]") + q

    def url(m):
        user, pw = m.group("user"), m.group("pw")
        if pw:
            return m.group("keep") + user + ":" + hold("[redacted]") + "@"
        return m.group("keep") + (hold("[redacted]") if looks_random(user) or PREFIXED.fullmatch(user) else user) + "@"

    text = HEADER.sub(lambda m: m.group("keep") + hold("[redacted]"), text)
    text = FLAG.sub(keep_named, text)
    text = FISH.sub(keep_named, text)
    text = PAIR.sub(pair, text)
    text = URL_AUTH.sub(url, text)
    text = PREFIXED.sub(lambda m: hold("[redacted]"), text)
    text = RUN.sub(lambda m: hold("[redacted]") if looks_random(m.group(0)) else m.group(0), text)
    text = PROSE_PASSWORD.sub(lambda m: m.group(0) if not secret_value(m.group("val"), prose) else m.group("keep") + hold("[redacted]"), text)
    # redact.py's shapes (keys, tokens, JWTs, cards, recovery phrases...); its password and secret phrasings are what
    # the name-and-value checks above do here, without taking `$(security ...)` or "the api_key field" for one.
    for start, end in reversed(redact_module._seed_phrases(text)):
        text = text[:start] + hold("[redacted recovery phrase]") + text[end:]
    for kind, pat in SHAPES:
        text = pat.sub(lambda m, k=kind: (m.groupdict().get("keep") or "") + hold(f"[redacted {k}]"), text)
    return re.sub("\x00(\\d+)\x00", lambda m: kept[int(m.group(1))], re.sub("\x00(\\d+)\x00", lambda m: kept[int(m.group(1))], text))


def run(cmd, timeout=20):
    """A read-only command's output, or None when it isn't installed or fails."""
    if not shutil.which(cmd[0]) and not os.path.exists(cmd[0]):
        return None
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, errors="replace", timeout=timeout)
    except (OSError, subprocess.TimeoutExpired):
        return None
    return r.stdout if r.returncode == 0 else None


def tilde(p):
    p = str(p)
    return "~" + p[len(str(HOME)):] if p == str(HOME) or p.startswith(str(HOME) + "/") else p


class Versions:
    """Every version of each thing, so a new one carries what changed and an unchanged one is left as it was.

    The newest version of a thing is the one first seen last (meta.seen), not the newest file time: a config
    restored from a backup keeps its old time. A thing back to an earlier text is a new version of its own. Every
    run re-redacts the versions it keeps, so a secret an earlier, weaker rule let through is taken out of them too."""

    def __init__(self):
        self.old, self.latest = [], {}
        p = NORM / "setup.jsonl"
        if p.exists():
            for line in p.open(encoding="utf-8", errors="replace"):
                try:
                    r = json.loads(line)
                except ValueError:
                    continue
                m = r.get("meta") if isinstance(r, dict) else None
                if not isinstance(m, dict) or not m.get("what") or m.get("generated"):
                    continue
                self.old.append(r)
                k, when = m["what"], m.get("seen") or r.get("ts") or ""
                if k not in self.latest or when > (self.latest[k]["meta"].get("seen") or self.latest[k].get("ts") or ""):
                    self.latest[k] = r  # a tie keeps the first: the file holds the newest run's records first
        self.ids = {r.get("id") for r in self.old}

    def add(self, w, what, kind, title, raw, ts, meta, prose=False):
        """raw: the thing's text as read, secrets and all; it's redacted here, and only redacted text is kept."""
        raw = raw.strip()
        digest = hashlib.sha256(raw.encode()).hexdigest()[:16]
        text = redact(raw if len(raw) <= CAP else raw[:CAP], prose).strip() + ("\n[cut: longer than this]" if len(raw) > CAP else "")
        meta = {"what": what, **meta, "digest": digest}
        # A file a program writes for itself ("generated by", "do not edit") is kept as it is now, not every version.
        if kind == "config" and GENERATED.search("\n".join(raw.splitlines()[:5])):
            self.write(w, id=f"{what}@latest", kind=kind, ts=ts or NOW, title=title, text=text, meta={**meta, "generated": True, "seen": NOW})
            return
        before = self.latest.get(what)
        if before and ((before["meta"].get("digest") == digest) if before["meta"].get("digest") else before.get("text") == text):
            return  # unchanged: the version already kept stays as it was (re-redacted in finish)
        rid, n = f"{what}@{digest}", 1
        while rid in self.ids or w.has(rid):  # back to an earlier text: a new version all the same
            rid, n = f"{what}@{digest}.{n}", n + 1
        meta["seen"] = NOW
        if before:
            diff = list(difflib.unified_diff((before.get("text") or "").splitlines(), text.splitlines(), lineterm="", n=0))[2:]
            meta["changed"] = {"from": before["id"], "added": sum(1 for d in diff if d.startswith("+")),
                               "removed": sum(1 for d in diff if d.startswith("-")),
                               "diff": "\n".join(d for d in diff if not d.startswith("@@"))[:4000]}
            title = f"Changed: {title}"
        self.write(w, id=rid, kind=kind, ts=ts or NOW, title=title, text=text, meta=meta)

    def write(self, w, meta, **rec):
        w.add(author="me", is_me=True, thread=f"setup:{meta.get('group')}", thread_name=(meta.get("group") or "setup").capitalize(),
              meta=meta, **rec)

    def finish(self, w):
        """The versions kept from earlier runs, written again with today's redaction."""
        for r in self.old:
            if w.has(r.get("id")):
                continue
            m = dict(r["meta"])
            prose = str(m.get("path") or "").endswith(".md")
            if isinstance(m.get("changed"), dict) and m["changed"].get("diff"):
                m["changed"] = {**m["changed"], "diff": redact(m["changed"]["diff"], prose)}
            w.add(**{**{k: r[k] for k in FIELDS if k in r and k != "source"}, "text": redact(r.get("text") or "", prose), "meta": m})


