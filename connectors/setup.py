# Secrets in configs. A setting is redacted when its name says secret (token, api_key, clientSecret, password, auth...)
# and its value looks like one (not a number, a flag, an env var's name, a path, a <placeholder>); in any syntax:
# JSON, YAML, TOML, shell and fish, Lua, a command's --flag, an MCP server's args. Then shapes whatever their name:
# known prefixes, credentials in URLs and headers, long random-looking runs, and redact.py's (keys, tokens, cards,
# recovery phrases). What's already [redacted] stays as it is, so redacting twice changes nothing.
SECRET_WORDS = re.compile(r"(?:^|_)(?:api_?key|apikey|access_?key|secret|secrets|token|tokens|passw(?:or)?d|passwd|pwd|passphrase|"
                          r"credentials?|private_?key|auth|authorization|bearer|cookie|session_?key|signing_?key|key)$|"
                          r"(?:^|_)(?:api_?key|secret|token|password|passwd|credential)(?:_|$)")
NOT_SECRET_NAME = re.compile(r"(?:^|_)(?:max|min|num|limit|budget|count|thinking|output|input|context)(?:_|$)|keybind|keymap|hotkey|"
                             r"key_?bindings?|^env_?key$|_(?:path|file|name|names|id|ids|url|cmd|command|helper|type|length|"
                             r"size|prefix|header|env|var)$|public_?key|publishable|^key_?(?:code|repeat|equivalents)")
