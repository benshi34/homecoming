FLAG = re.compile(r"""(?<![\w-])(?P<keep>--?(?P<name>[A-Za-z][\w-]{1,40})(?:=|\s+|["']\s*,\s*))(?P<val>"[^"\n]*"|'[^'\n]*'|[^\s"',\]]+)""")
FISH = re.compile(r"(?m)(?P<keep>\bset\s+(?:-[a-zA-Z]+\s+)+(?P<name>[A-Za-z_]\w*)\s+)(?P<val>\S+)")
